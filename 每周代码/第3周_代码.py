from ugot import ugot
import time

ug = ugot.UGOT()
ug.initialize("192.168.x.x")   # ←←← 换成你的机器人 IP
ug.set_volume(60)

def 安全收尾():
    # 每个场景跑完都叫它一声：停车 + 关灯 + 擦屏幕
    ug.stop_chassis()
    ug.turn_off_lights()
    ug.screen_clear()

# ============ 先造按钮（本周核心：def 函数）============

前进 = 0    # 方向常量：给数字起个好记的名字（前进0/后退1/左转2/右转3）
后退 = 1
左转 = 2
右转 = 3

def 走(秒数, 速度=40):
    # 前进按钮：机器人走"秒数"秒自己停；_times 不阻塞 Python，所以要陪等
    ug.balance_move_speed_times(前进, 速度, 秒数, 0)   # 单位只认 0=秒 / 1=厘米
    time.sleep(秒数)                                   # ★ 没这行，路线会挤成一团

def 倒(秒数, 速度=40):
    # 后退按钮：和"走"只差方向常量
    ug.balance_move_speed_times(后退, 速度, 秒数, 0)
    time.sleep(秒数)

def 转(方向, 秒数, 速度=120):
    # 转弯按钮（按秒）：想转得准就用下面的"转90度"
    ug.balance_turn_speed_times(方向, 速度, 秒数, 0)   # 单位只认 0=秒 / 2=度
    time.sleep(秒数)

def 转90度(方向, 速度=120):
    # 精准转弯按钮：用"度"当单位。转弯速度 5~360，90÷速度≈要转几秒
    ug.balance_turn_speed_times(方向, 速度, 90, 2)     # 单位 2 = 度
    time.sleep(90 / 速度 + 0.3)                        # 度数÷速度，再加 0.3 秒余量

def 平衡车准备():
    # 每个运动场景的第一句：先喊它站起来，等 2 秒站稳再谈走路
    ug.balance_start_balancing()
    time.sleep(2)

def 平衡车收工():
    # 每个运动场景的最后一句：退出自平衡（往后倒，扶一下！）+ 通用收尾
    ug.stop_chassis()
    ug.balance_stop_balancing()
    安全收尾()

# ============ 课堂代码复现 ============

def 场景1_开场白_亮屏确认():
    # 跑这个你会看到：屏幕绿字「平衡车就绪」+ 笑脸表情，确认连接没问题（不运动）
    ug.screen_print_text("平衡车就绪", 6)        # 6 = 绿
    ug.screen_display_emotion("Smile")           # 表情名是字符串
    time.sleep(2)
    安全收尾()

def 场景2_四个按钮试一遍():
    # 跑这个你会看到：站起来 → 前进1秒 → 后退1秒 → 左转1秒 → 右转1秒，一段一段不卡壳
    # ⚠️ 运动！平衡车怕地毯边/拖鞋/电线，先清场
    平衡车准备()
    走(1)          # ① 前进 1 秒
    倒(1)          # ② 后退 1 秒
    转(左转, 1)    # ③ 左转 1 秒
    转(右转, 1)    # ④ 右转 1 秒
    平衡车收工()

def 场景3_课堂项目_L形路线():
    # 跑这个你会看到：直走 2 秒 → 原地左转 → 再直走 2 秒，走成一个「└」形小路
    # 💡 想看"不陪等"的乱象：把按钮里的 time.sleep 那行注释掉再跑一次（看完恢复！）
    平衡车准备()
    走(2)          # ① 前进 2 秒
    转(左转, 1)    # ② 左转 1 秒
    走(2)          # ③ 再前进 2 秒
    平衡车收工()

# ============ 趣味加餐 ============

def 彩蛋1_口字路线():
    # 跑这个你会看到：走 2 秒 + 右转 90 度，重复 4 次——理论上正好回到出发点，
    #                 看它最后偏了多少，那就是"积少成多"的误差
    平衡车准备()
    走(2)
    转90度(右转)
    走(2)
    转90度(右转)
    走(2)
    转90度(右转)
    走(2)
    转90度(右转)
    平衡车收工()

def 彩蛋2_小碎步舞蹈():
    # 跑这个你会看到：前进后退交替 + 左右小角度摆头 45 度，像在原地蹦迪
    平衡车准备()
    走(1)
    倒(1)
    ug.balance_turn_speed_times(左转, 200, 45, 2)   # 左摆 45 度（转速上限 360）
    time.sleep(45 / 200 + 0.3)                       # 45÷200≈0.23 秒，加余量
    走(1)
    ug.balance_turn_speed_times(右转, 200, 45, 2)   # 右摆 45 度
    time.sleep(45 / 200 + 0.3)
    倒(1)
    平衡车收工()

def 彩蛋3_加速度对比():
    # 跑这个你会看到：同一条路走两遍——先"温柔起步"再"弹射起步"，差别肉眼可见
    平衡车准备()
    ug.balance_set_acceleration(10)      # 加速度调小：起步慢吞吞（必须是正数，≤0 它悄悄不理你）
    走(2)
    倒(1)
    ug.balance_set_acceleration(60)      # 加速度调大：起步一下窜出去
    走(2)
    倒(1)
    ug.balance_reset_acceleration()      # 用完一定恢复默认，别把"弹射"留给下一局
    平衡车收工()

